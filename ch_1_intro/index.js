//history of node js 
//2009 – Node.js was created by Ryan Dahl
//👉 Built on Google Chrome’s V8 JavaScript engine
//2010 – npm (Node Package Manager) was introduced
//2011–2014 – Node.js became popular for real-time apps
//2015 – Node.js Foundation was formed
//2019–Present – Node.js widely used for backend, APIs, microservices, and full-stack apps

//**********Why Node.js Was Created************

// Traditional servers handle requests one by one, which is slow.
// Node.js introduced:
// Non-blocking
// Event-driven
// Asynchronous processing

//advantages
// 1️⃣ Fast Performance
// Uses V8 engine
// Executes code very quickly

// 2️⃣ Asynchronous & Non-Blocking
// Does not wait for one task to finish
// Handles multiple requests together

// 3️⃣ Single Language (JavaScript)
// Same language for frontend + backend
// Easy for web developers

// 4️⃣ Huge Package Ecosystem
// npm provides millions of packages
// Saves development time

// 5️⃣ Best for Real-Time Applications
// Chat apps 
// Live notifications 
// Online games 

// 6️⃣ Scalable
// Easy to scale for large applications
// Used by big companies

//Node.js is a JavaScript runtime introduced in 2009 
//that allows developers to build fast, scalable, and non-blocking server-side applications.